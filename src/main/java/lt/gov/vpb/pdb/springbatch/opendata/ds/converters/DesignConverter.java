package lt.gov.vpb.pdb.springbatch.opendata.ds.converters;

import lt.vpb.open_data.schemas.design.v1_2.DesignCurrentStatusCodeType;
import lt.vpb.open_data.schemas.design.v1_2.DesignRepresentationSheetType;
import lt.vpb.open_data.schemas.design.v1_2.DesignType;
import lt.vpb.open_data.schemas.design.v1_2.URIType;
import lt.vpb.open_data.schemas.iso3166_1_extended_country_code.v1_1.ISO3166CountryCode;
import lt.vpb.open_data.schemas.iso639_language_code.v1.ISO639LanguageCodeType;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;
import org.springframework.web.util.UriTemplate;
import org.tmdn.cti.exception.ConversionError;
import org.tmdn.cti.repository.jpa.domain.design.Design;
import org.tmdn.cti.repository.jpa.domain.design.DesignImage;

import java.util.List;

import static org.apache.commons.lang.StringUtils.isBlank;
import static org.apache.commons.lang.StringUtils.leftPad;
import static org.springframework.util.CollectionUtils.isEmpty;


@Component
public class DesignConverter {

	@Autowired
	private PersonConverter personConverter;

	@Autowired
	private ClassificationConverter classificationConverter;

	@Autowired
	private IndicatorProductConverter indicatorProductConverter;

	@Autowired
	private PriorityDetailsConverter priorityDetailsConverter;

	@Autowired
	private PublicationDetailsConverter publicationDetailsConverter;

	@Autowired
	private ExhibitionPriorityConverter exhibitionPriorityConverter;

	@Autowired
	private RecordConverter recordConverter;

	@Autowired
	private ImageConverter imageConverter;

	@Autowired
	private ST13Generator st13Generator;

	@Value("${opendata.ds.image-uri-template}")
	private UriTemplate designUriPrefix;

	public DesignType convert(Design design, List<ConversionError> errors) {
		DesignType designType = new DesignType();
		if (design == null) {
			return designType;
		}
		if(!isBlank(design.getApplicationReference())) {
			designType.withApplicationReference(design.getApplicationReference());
		}
		designType.withApplicationDate(design.getApplicationDate());
		if(!isBlank(design.getApplicationLanguageCode())) {
			designType.withApplicationLanguageCode(ISO639LanguageCodeType.fromValue(design.getApplicationLanguageCode().toLowerCase()));
		}
		if(!isBlank(design.getDesignDescription())) {
			designType.withDesignDescription(design.getDesignDescription());
		}
		designType.withDesignCurrentStatusDate(design.getStatusDate());
		designType.withApplicationNumber(design.getApplicationNumber());
		designType.withApplicationPublicationDate(design.getPublicationDate());

		if (design.getCurrentStatus() != null) {
			designType
					.withDesignCurrentStatusCode(DesignCurrentStatusCodeType
							.fromValue(design.getCurrentStatus().trim()));
		}

		//TODO: Review if this doesnt affect the number of designs generated by CTI
		designType.setDesignIdentifier(design.getRegistrationNumber().trim() + "-" + leftPad(design.getDesignIdentifier(), 4, "0"));
		designType.setPublicationDate(design.getPublicationDate());
		designType.setEffectiveDate(design.getEffectiveDate());
		designType.setExpiryDate(design.getExpiryDate());
		designType.setRegistrationDate(design.getRegistrationDate());
		designType.setRegistrationNumber(design.getRegistrationNumber());
		if(!isEmpty(design.getIndicationProducts())){
			designType.withIndicationProductDetails(indicatorProductConverter.convert(design.getIndicationProducts()));
		}

		if (design.getRegistrationOfficeCode() != null) {
			designType.withRegistrationOfficeCode(
					ISO3166CountryCode
					.fromValue(design.getRegistrationOfficeCode())
					.value());
		}

		String designSt13 = st13Generator.forDesign(design);
		designType.setDesignURI(new URIType().withValue(designUriPrefix.expand(designSt13).toString()));

		if(!isEmpty(design.getApplicants())){
			designType.withApplicantDetails(personConverter.toApplicantDetails(design));
		}

		if(!isEmpty(design.getClassifications())){
			designType.withClassDescriptionDetails(classificationConverter.convert(design.getClassifications()));
		}

		if(design.getPriorities()!= null){
			designType.withPriorityDetails(priorityDetailsConverter.convert(design.getPriorities()));
		}

		if(design.getPublications()!=null) {
			designType.withPublicationDetails(publicationDetailsConverter.convert(design.getPublications()));
		}

		if(!isEmpty(design.getExhibitionPriorities())){
			designType.withExhibitionPriorityDetails(exhibitionPriorityConverter.convert(design.getExhibitionPriorities()));
		}

		if(!isEmpty(design.getRecords())){
			designType.withDesignRecordDetails(recordConverter.convert(design.getRecords()));

		}

		if(!isEmpty(design.getRepresentatives())){
			designType.withRepresentativeDetails(personConverter.toRepresentativeDetails(design));
		}

		for(DesignImage image: design.getImages()) {
			if(image.getPreferedIndicator() != null && image.getPreferedIndicator().intValue()==1){
				designType.withDesignPreferedRepresentation(imageConverter.convert(image, design, designSt13));
			}
		}

		if (!isEmpty(design.getImages())) {
			designType.withDesignRepresentationSheetDetails(new DesignType.DesignRepresentationSheetDetails()
					.withDesignRepresentationSheet(new DesignRepresentationSheetType()
							.withViewDetails(imageConverter.convert(design.getImages(), design, designSt13))));
		}

		return designType;
	}
}
